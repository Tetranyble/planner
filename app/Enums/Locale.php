    /**
     * Get the human-readable display name (e.g., "English (Nigeria)").
     */
    public function label(?self $inLocale = null): string
    {
        return IntlLocale::getDisplayName($this->value, $inLocale?->value ?? $this->value);
    }

    /**
     * Format a date using this locale's native rules.
     */
    public function formatDate(
        DateTimeInterface $date,
        int $dateStyle = IntlDateFormatter::SHORT,
        int $timeStyle = IntlDateFormatter::NONE
    ): string {
        $formatter = new IntlDateFormatter($this->value, $dateStyle, $timeStyle);

        return $formatter->format($date);
    }

    /**
     * Format a monetary amount using this locale's native formatting.
     */
    public function formatCurrency(float $amount, Currency $currency = Currency::NGN): string
    {
        $formatter = new NumberFormatter($this->value, NumberFormatter::CURRENCY);

        return $formatter->formatCurrency($amount, $currency->value);
    }
